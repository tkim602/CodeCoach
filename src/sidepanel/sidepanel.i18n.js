export function normalizeUiLanguage(language) {
  const value = String(language || "").toLowerCase();
  return value.startsWith("en") ? "en" : "ko";
}

export function resolveUiLanguage({ settingsLanguage, selectedLanguage } = {}) {
  return normalizeUiLanguage(settingsLanguage || selectedLanguage || "ko");
}

export function createTranslator(getLanguage) {
  return function translate(key) {
    const language = typeof getLanguage === "function" ? getLanguage() : getLanguage;
    const lang = normalizeUiLanguage(language);
    return (I18N[lang]?.[key] ?? I18N.ko[key]) ?? key;
  };
}

export function applyStaticLocalization(documentRef, language) {
  const lang = normalizeUiLanguage(language);
  documentRef.documentElement.lang = lang;
  documentRef.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (I18N[lang]?.[key]) node.textContent = I18N[lang][key];
  });
  documentRef.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (I18N[lang]?.[key]) {
      if (node.contentEditable === "true") {
        node.dataset.placeholder = I18N[lang][key];
      } else {
        node.placeholder = I18N[lang][key];
      }
    }
  });
  documentRef.querySelectorAll("[data-i18n-tooltip]").forEach((node) => {
    const key = node.dataset.i18nTooltip;
    if (I18N[lang]?.[key]) node.dataset.tooltip = I18N[lang][key];
  });
  documentRef.querySelectorAll("[data-i18n-title]").forEach((node) => {
    const key = node.dataset.i18nTitle;
    if (I18N[lang]?.[key]) node.title = I18N[lang][key];
  });
  documentRef.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
    const key = node.dataset.i18nAriaLabel;
    if (I18N[lang]?.[key]) node.setAttribute("aria-label", I18N[lang][key]);
  });
  return lang;
}
